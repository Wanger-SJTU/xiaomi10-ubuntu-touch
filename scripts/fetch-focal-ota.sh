#!/usr/bin/env bash
# 下载 Ubuntu Touch 20.04 (Focal) OTA rootfs 并组装 ota-focal/ 目录。
#
# 频道: 20.04/arm64/android9plus/stable
# 说明: 该频道的 rootfs 是设备无关的 pool 文件；我们只需要 rootfs + version，
#       halium/device tarball 由本工程自行构建/提供（见 README §4.2/§4.5）。
#
# 用法: bash scripts/fetch-focal-ota.sh [输出目录, 默认 ota-focal]
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$HERE/ota-focal}"
BASE=https://system-image.ubports.com
CHANNEL=20.04/arm64/android9plus/stable
DONOR=miatoll

# 代理（如需）:
#   export http_proxy=http://127.0.0.1:7890 https_proxy=http://127.0.0.1:7890

mkdir -p "$OUT"; cd "$OUT"

echo "==> 获取 index.json"
curl -fsSL --retry 3 -o index.json "$BASE/$CHANNEL/$DONOR/index.json"

echo "==> 解析最新 full 版本"
python3 - <<'PY'
import json
d = json.load(open('index.json'))
imgs = [i for i in d['images'] if i['type'] == 'full']
imgs.sort(key=lambda i: i['version'])
latest = imgs[-1]
print("version:", latest['version'], latest['description'])
with open('files.list', 'w') as f:
    for x in latest['files']:
        f.write(f"{x['order']} {x['size']} {x['path']} {x['checksum']} {x['signature']}\n")
PY
cat files.list

echo "==> 下载 rootfs 与 version"
rootfs=$(awk '{print $3}' files.list | grep -E '/rootfs-' | head -1)
version=$(awk '{print $3}' files.list | grep -E '/version-' | head -1)
[ -n "$rootfs" ] && [ -n "$version" ] || { echo "index 里找不到 rootfs/version"; exit 1; }

curl -fL --retry 3 -C - -o rootfs.tar.xz "$BASE$rootfs"
curl -fL --retry 3 -C - -o version.tar.xz "$BASE$version"

echo "==> 校验 sha256"
want=$(awk '{print $4}' files.list | head -1)
got=$(sha256sum rootfs.tar.xz | awk '{print $1}')
echo "want=$want"; echo "got =$got"
[ "$want" = "$got" ] || { echo "rootfs 校验失败"; exit 1; }

echo "==> 准备 ubuntu_command（签名校验已在 make-rootfs-noroot.sh 中关闭）"
touch rootfs.tar.xz.asc version.tar.xz.asc
cat > ubuntu_command <<'EOF'
# Generated by xiaomi10-ubuntu-touch build scripts
format system
load_keyring image-master.tar.xz image-master.tar.xz.asc
load_keyring image-signing.tar.xz image-signing.tar.xz.asc
mount system
update rootfs.tar.xz rootfs.tar.xz.asc
update halium_halium_arm64.tar.xz halium_halium_arm64.tar.xz.asc
update device_umi.tar.xz device_umi.tar.xz.asc
update version.tar.xz version.tar.xz.asc
unmount system
EOF
ls -lh
echo "==> 完成。下一步：把 halium 与 device tarball 放到本目录后运行"
echo "    bash scripts/make-rootfs-noroot.sh $OUT out"
